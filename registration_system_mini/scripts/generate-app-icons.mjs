// Reuses the admin workspace's existing Lucide and Playwright; adds no app dependency.
import { mkdir, writeFile } from 'node:fs/promises';
import { deflateSync } from 'node:zlib';
import { chromium } from '../../registration_system_backend_fe_go/node_modules/playwright/index.mjs';
import { appIconNames, appIconTones, footballNode, tabIcons } from './app-icon-config.mjs';

const output = new URL('../src/static/app-icons/', import.meta.url);
const source = new URL('../../registration_system_backend_fe_go/node_modules/lucide-react/dist/esm/icons/', import.meta.url);

// A 128-step alpha palette limits coverage rounding to 1/255 and avoids RGBA
// screenshot overhead in the limited mini-program pack.
function alphaPng(alpha, color) {
  const chunk = (type, data) => {
    const payload = Buffer.concat([Buffer.from(type), data]);
    let crc = 0xffffffff;
    for (const value of payload) {
      crc ^= value;
      for (let bit = 0; bit < 8; bit++) crc = (crc >>> 1) ^ ((crc & 1) ? 0xedb88320 : 0);
    }
    const result = Buffer.alloc(data.length + 12);
    result.writeUInt32BE(data.length);
    payload.copy(result, 4);
    result.writeUInt32BE((crc ^ 0xffffffff) >>> 0, result.length - 4);
    return result;
  };
  const header = Buffer.alloc(13);
  header.writeUInt32BE(72, 0); header.writeUInt32BE(72, 4);
  header[8] = 8; header[9] = 3;
  const rgb = Buffer.from(color.slice(1), 'hex');
  const palette = Buffer.concat(Array.from({ length: 128 }, () => rgb));
  const rows = Buffer.alloc(73 * 72);
  for (let y = 0; y < 72; y++) Buffer.from(alpha.slice(y * 72, (y + 1) * 72)
    .map(value => Math.round(value * 127 / 255))).copy(rows, y * 73 + 1);
  return Buffer.concat([Buffer.from('89504e470d0a1a0a', 'hex'), chunk('IHDR', header),
    chunk('PLTE', palette), chunk('tRNS', Buffer.from(Array.from({ length: 128 }, (_, i) => Math.round(i * 255 / 127)))),
    chunk('IDAT', deflateSync(rows, { level: 9 })), chunk('IEND', Buffer.alloc(0))]);
}
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true, executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH });
try {
  const page = await browser.newPage({ viewport: { width: 72, height: 72 }, deviceScaleFactor: 1 });
  for (const name of appIconNames) {
    // Match the approved homepage's unobstructed statistics bars.
    const original = { 'chart-column': 'chart-no-axes-column', 'circle-help': 'circle-question-mark' }[name] ?? name;
    const node = name === 'football' ? footballNode : (await import(new URL(`${original}.js`, source))).__iconNode;
    const shapes = node.map(([tag, attributes]) => `<${tag} ${Object.entries(attributes)
      .filter(([key]) => key !== 'key').map(([key, value]) => `${key}="${value}"`).join(' ')}/>`).join('');
    const tones = { ...appIconTones, ...(Object.values(tabIcons).includes(name) ? { active: '#00cfb3', inactive: '#8c96a5' } : {}) };
    // One editable SVG per icon; runtime PNG variants provide native image colors.
    const svg = stroke => `<svg xmlns="http://www.w3.org/2000/svg" width="72" height="72" viewBox="0 0 24 24" fill="none" stroke="${stroke}" stroke-width="1.65" stroke-linecap="round" stroke-linejoin="round">${shapes}</svg>\n`;
    await writeFile(new URL(`${name}.svg`, output), svg('currentColor'));
    for (const [tone, color] of Object.entries(tones)) {
      await page.setContent(`<style>html,body{margin:0;width:72px;height:72px;overflow:hidden}svg{display:block}</style>${svg(color)}`);
      const alpha = await page.evaluate(async () => {
        const svg = document.querySelector('svg');
        const image = new Image();
        image.src = `data:image/svg+xml;charset=utf-8,${encodeURIComponent(svg.outerHTML)}`;
        await image.decode();
        const canvas = document.createElement('canvas');
        canvas.width = 72; canvas.height = 72;
        const context = canvas.getContext('2d');
        context.drawImage(image, 0, 0);
        return Array.from(context.getImageData(0, 0, 72, 72).data).filter((_, i) => i % 4 === 3);
      });
      await writeFile(new URL(`${name}-${tone}.png`, output), alphaPng(alpha, color));
    }
  }
} finally {
  await browser.close();
}
await writeFile(new URL('../src/components/ui/appIconNames.ts', import.meta.url),
  `// Generated by scripts/generate-app-icons.mjs.\nexport const appIconNames = ${JSON.stringify(appIconNames, null, 2)} as const;\n\nexport type AppIconName = typeof appIconNames[number];\n`);
console.log(`Generated ${appIconNames.length} native icons and four tab color pairs.`);
