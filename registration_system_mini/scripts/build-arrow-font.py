"""Generate the WeChat arrow font from the editable SVG (requires fonttools 4.x)."""

import base64
import io
import math
from pathlib import Path
import xml.etree.ElementTree as ET

from fontTools.fontBuilder import FontBuilder
from fontTools.pens.cu2quPen import Cu2QuPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.ttGlyphPen import TTGlyphPen
from fontTools.svgLib.path import parse_path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "src/static/icons/dotted-arrow.svg"
OUTPUT = ROOT / "src/styles/arrow-font.css"
NS = "{http://www.w3.org/2000/svg}"

# Match Wot 2.3 directional codepoints as well as existing text arrows.
CODEPOINTS = {
    "right": [0x2192, 0x203A, 0xE815, 0xE804, 0xE811],
    "left": [0x2190, 0x2039, 0xE818, 0xE80C, 0xE816],
    "down": [0x2193, 0x2304, 0xE817, 0xE814, 0xE80F],
    "up": [0x2191, 0x2303, 0xE802, 0xE6ED, 0xE6EA],
    "doubleRight": [0x00BB, 0xE812],
    "doubleLeft": [0x00AB, 0xE810],
    "doubleDown": [0xE813],
    "doubleUp": [0xE6E9],
}


def draw_source(pen, root, double=False):
    for node in root:
        if node.tag == NS + "path":
            parse_path(node.attrib["d"], pen)
            if double:
                parse_path(node.attrib["d"], TransformPen(pen, (1, 0, 0, 1, 60, 0)))
        elif node.tag == NS + "circle":
            x, y, r = (float(node.attrib[key]) for key in ("cx", "cy", "r"))
            k = r * 0.5522847498
            pen.moveTo((x + r, y))
            pen.curveTo((x + r, y + k), (x + k, y + r), (x, y + r))
            pen.curveTo((x - k, y + r), (x - r, y + k), (x - r, y))
            pen.curveTo((x - r, y - k), (x - k, y - r), (x, y - r))
            pen.curveTo((x + k, y - r), (x + r, y - k), (x + r, y))
            pen.closePath()


def make_glyph(root, name):
    double = name.startswith("double")
    width = 232 if double else 172
    scale = 1000 / width
    angle = {"right": 0, "left": 180, "up": 90, "down": -90}[
        name.removeprefix("double").lower()
    ]
    radians = math.radians(angle)
    c, s = math.cos(radians), math.sin(radians)
    # First fit the reference into a square em, then rotate around its centre.
    tx, ty = -width / 2, -44
    transform = (
        c * scale, s * scale, s * scale, -c * scale,
        500 + scale * (c * tx + s * ty),
        500 + scale * (s * tx - c * ty),
    )
    pen = TTGlyphPen(None)
    draw_source(Cu2QuPen(TransformPen(pen, transform), max_err=0.5, reverse_direction=True), root, double)
    return pen.glyph()


def main():
    root = ET.parse(SOURCE).getroot()
    builder = FontBuilder(1000, isTTF=True)
    builder.setupGlyphOrder([".notdef", *CODEPOINTS])
    builder.setupCharacterMap({code: name for name, codes in CODEPOINTS.items() for code in codes})
    builder.setupGlyf({".notdef": TTGlyphPen(None).glyph(), **{
        name: make_glyph(root, name) for name in CODEPOINTS
    }})
    builder.setupHorizontalMetrics({name: (1000, getattr(glyph, "xMin", 0))
                                    for name, glyph in builder.font["glyf"].glyphs.items()})
    builder.setupHorizontalHeader(ascent=1000, descent=0)
    builder.setupNameTable({"familyName": "MatchArrows", "styleName": "Regular",
                           "uniqueFontIdentifier": "MatchArrows-Regular-v1",
                           "fullName": "MatchArrows Regular", "psName": "MatchArrows-Regular"})
    builder.setupOS2(sTypoAscender=1000, sTypoDescender=0, usWinAscent=1000, usWinDescent=0)
    builder.setupPost()
    builder.font.recalcTimestamp = False
    builder.font["head"].created = builder.font["head"].modified = 2082844800
    builder.font.flavor = "woff"
    data = io.BytesIO()
    builder.font.save(data)
    encoded = base64.b64encode(data.getvalue()).decode("ascii")
    names = ["arrow-right", "right", "caret-right", "arrow-left", "left", "caret-left",
             "arrow-up", "up", "caret-up", "arrow-down", "down", "caret-down",
             "double-right", "double-left", "double-up", "double-down"]
    selectors = ",\n".join(f".wd-icon.wd-icon-{name}::before" for name in names)
    OUTPUT.write_text(
        "/* Generated by scripts/build-arrow-font.py from static/icons/dotted-arrow.svg.\n"
        "   Imported only for MP-WEIXIN; embedded to avoid network/font-loading dependencies. */\n"
        "@font-face {\n  font-family: 'MatchArrows';\n"
        f"  src: url('data:font/woff;base64,{encoded}') format('woff');\n"
        "  font-weight: normal;\n  font-style: normal;\n}\n\n"
        ".ui-arrow-text {\n  font-family: 'MatchArrows', 'PingFang SC', 'Helvetica Neue', sans-serif;\n"
        "  font-synthesis: none;\n}\n\n"
        f"{selectors} {{\n  font-family: 'MatchArrows' !important;\n}}\n",
        encoding="utf-8",
    )
    print(f"Generated {OUTPUT.relative_to(ROOT)} ({len(data.getvalue())} byte WOFF)")


if __name__ == "__main__":
    main()
